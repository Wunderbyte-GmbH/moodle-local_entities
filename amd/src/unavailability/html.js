/**
 * Makes a text safe for HTML.
 *
 * @param {string} text
 * @returns {string}
 */
export const escapeHtml = (text) => String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
